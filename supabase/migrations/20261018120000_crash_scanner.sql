-- DAILY CRASH SCANNER (Nik, 18 Oct 2026; research in research/crash-scan/).
-- crash-scan flags any universe stock that closes 15%+ below the day before, pushes a heads-up,
-- and on day 2 near 3:30 PM New York pushes the A+B trade (sell puts 2% out, about $100K of strike,
-- nearest expiry at least 3 days out; at most 5 crash trades open). Every suggestion is kept; `taken`
-- is set when IBKR shows puts sold on that name on day 2, so the scoreboard can show both.

create table if not exists public.crash_universe (
  ticker text primary key,
  added  date not null default current_date
);

create table if not exists public.crash_events (
  id          bigserial primary key,
  ticker      text not null,
  day         date not null,               -- the crash session
  prev_close  numeric not null,
  close       numeric not null,
  drop_pct    numeric not null,            -- close-to-close, negative
  entry_day   date not null,               -- day 2: the next session
  suggestion  jsonb,                       -- the day-2 trade as pushed: expiry, strike, contracts, bid, ask, mid, spot
  taken       boolean,                     -- puts sold on this name on day 2 (from option_trades)
  paper       jsonb,                       -- paper result of the A+B wheel, filled later (step 4)
  book_id     text not null default 'S',
  created_at  timestamptz not null default now(),
  unique (ticker, day)
);
create index if not exists crash_events_entry_idx on public.crash_events (entry_day);

alter table public.crash_universe enable row level security;
alter table public.crash_events enable row level security;
create policy "crash_universe: signed-in read" on public.crash_universe for select to authenticated using (true);
create policy "crash_events: book members read" on public.crash_events for select to authenticated
  using (book_id in (select public.my_books()));

